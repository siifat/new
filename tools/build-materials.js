#!/usr/bin/env node
/* Scans ./materials/ and writes ./assets/js/materials-index.js
   Usage:  node tools/build-materials.js
*/
const fs   = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const MAT  = path.join(ROOT, "materials");
const OUT  = path.join(ROOT, "assets", "js", "materials-index.js");

const LABELS = {
  slides: "Slides", "lecture-slides": "Slides", "web-deck": "Web Slides",
  notes: "Notes", "class-tests": "Class Tests", ct: "Class Tests",
  finals: "Final Questions", final: "Final Questions",
  assignments: "Assignments", assignment: "Assignments",
  labs: "Labs", lab: "Labs",
  books: "Books & References", references: "References",
  recordings: "Recordings", videos: "Videos",
  misc: "Miscellaneous"
};

const ORDER = ["slides","lecture-slides","web-deck","notes","class-tests","ct",
               "finals","final","assignments","assignment","labs","lab",
               "recordings","videos","books","references","misc"];

const humanSize = (b) =>
  b < 1024 ? b + " B"
  : b < 1048576 ? (b / 1024).toFixed(0) + " KB"
  : (b / 1048576).toFixed(1) + " MB";

function walk(dir, base) {
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    if (name.startsWith(".")) continue;
    const full = path.join(dir, name);
    const st = fs.statSync(full);
    if (st.isDirectory()) out.push(...walk(full, base));
    else {
      const rel = path.relative(base, full).split(path.sep).join("/");
      out.push({
        name,
        rel,
        href: "materials/" + path.basename(base) === "" ? rel : rel,
        size: humanSize(st.size),
        ext: path.extname(name).slice(1).toLowerCase()
      });
    }
  }
  return out;
}

function readMeta(courseDir) {
  const p = path.join(courseDir, "course.json");
  if (!fs.existsSync(p)) return {};
  try { return JSON.parse(fs.readFileSync(p, "utf8")); }
  catch (e) { console.warn("⚠  bad course.json in " + courseDir); return {}; }
}

function buildCourse(courseDir) {
  const slug = path.basename(courseDir);
  const meta = readMeta(courseDir);
  const skip = new Set((meta.hideFolders || []).concat(["node_modules", ".git"]));
  const entries = fs.readdirSync(courseDir, { withFileTypes: true });

  const sections = [];

  // top-level loose files
  const loose = entries
    .filter((e) => e.isFile() && e.name !== "course.json")
    .map((e) => {
      const st = fs.statSync(path.join(courseDir, e.name));
      return {
        name: e.name,
        href: "materials/" + slug + "/" + e.name,
        size: humanSize(st.size),
        ext: path.extname(e.name).slice(1).toLowerCase()
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (loose.length) sections.push({ name: "Files", folder: "", files: loose });

  // subfolders
  for (const e of entries) {
    if (!e.isDirectory() || skip.has(e.name) || e.name.startsWith(".")) continue;
    const sub = path.join(courseDir, e.name);
    const files = [];
    (function walkRel(d) {
      for (const n of fs.readdirSync(d)) {
        if (n.startsWith(".")) continue;
        const full = path.join(d, n);
        const st = fs.statSync(full);
        if (st.isDirectory()) { walkRel(full); continue; }
        const rel = path.relative(courseDir, full).split(path.sep).join("/");
        files.push({
          name: n,
          rel,
          href: "materials/" + slug + "/" + rel,
          size: humanSize(st.size),
          ext: path.extname(n).slice(1).toLowerCase()
        });
      }
    })(sub);
    if (!files.length) continue;
    files.sort((a, b) => a.name.localeCompare(b.name));
    sections.push({ name: LABELS[e.name] || e.name, folder: e.name, files });
  }

  sections.sort((a, b) => {
    const ai = ORDER.indexOf(a.folder); const bi = ORDER.indexOf(b.folder);
    return (ai < 0 ? 99 : ai) - (bi < 0 ? 99 : bi);
  });

  return {
    slug,
    code:        meta.code        || slug,
    title:       meta.title       || slug,
    description: meta.description || "",
    semester:    meta.semester    || "",
    instructor:  meta.instructor  || "",
    tags:        Array.isArray(meta.tags) ? meta.tags : [],
    order:       typeof meta.order === "number" ? meta.order : 100,
    sections
  };
}

(function build() {
  if (!fs.existsSync(MAT)) {
    console.log("No materials/ folder yet — writing an empty index.");
    fs.writeFileSync(OUT, "window.MATERIALS_INDEX = { generatedAt: null, courses: [] };\n");
    return;
  }
  const courses = fs.readdirSync(MAT, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith("."))
    .map((e) => buildCourse(path.join(MAT, e.name)))
    .sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));

  const payload = { generatedAt: new Date().toISOString(), courses };
  const js =
    "/* AUTO-GENERATED by tools/build-materials.js — do not edit. */\n" +
    "window.MATERIALS_INDEX = " + JSON.stringify(payload, null, 2) + ";\n";
  fs.writeFileSync(OUT, js);
  console.log("✔ wrote " + path.relative(ROOT, OUT) + "  (" + courses.length + " course(s))");
})();